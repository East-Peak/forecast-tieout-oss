KEEP = {"hires-only": "hires", "program-only": "programs"}


# ---------------------------------------------------------------- scenario plan files


def filter_plan(plan_text: str, scenario: str) -> str:
    """``plan.yaml`` with only the items the scenario keeps, under a header that
    says where it came from."""
    if scenario not in KEEP:
        raise ValueError(f"no filter for scenario {scenario!r}")
    doc = yaml.safe_load(plan_text) or {}
    kept = {KEEP[scenario]: doc.get(KEEP[scenario]) or []}
    body = yaml.safe_dump(kept, sort_keys=False, default_flow_style=False)
    return HEADER.format(source="plan.yaml", what=f"{KEEP[scenario]} only") + body


def scenario_plan_files(companies=COMPANIES) -> dict[Path, str]:
    out = {}
    for company in companies:
        demo = (REPO / PROFILES / company / "plan.yaml").read_text()
        for scenario in KEEP:
            out[PROFILES / company / f"plan-{scenario}.yaml"] = filter_plan(
                demo, scenario
            )
    return out


