"""Write the app's data: one report per company and named scenario, an index and a
comparison, under ``frontend/public/data/reports/``, and the TypeScript types for
them under ``frontend/src/generated/``.

The app calculates nothing: every number it shows is in one of these files, and
every file is produced by the core (``python -m engine.tieout_core``) at a fixed
as-of date, 2000 draws and seed 0. Four scenarios per company:

    as-signed        the roster as signed, nothing planned (no plan file)
    demo-plan        the company's committed ``plan.yaml``
    hires-only       ``plan.yaml``'s hires alone  (``plan-hires-only.yaml``)
    programme-only   ``plan.yaml``'s programmes alone  (``plan-programme-only.yaml``)

The last two plan files are committed beside ``plan.yaml``; this script writes
them by filtering ``plan.yaml``'s items and ``--verify`` fails if they drift.
Paths inside the files are repo-relative and keys are in a fixed order, so the
files are the same on every machine.

    python -m engine.scripts.generate_app_reports            # write everything
    python -m engine.scripts.generate_app_reports --verify   # regenerate to a temp dir, compare byte for byte
"""

from __future__ import annotations

import argparse
import contextlib
import json
import os
import subprocess
import sys
import tempfile
