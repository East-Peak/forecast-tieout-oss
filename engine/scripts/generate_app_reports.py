def comparison_rows(
    reports: dict[str, dict], labels: dict[str, str] | None = None
) -> list[dict]:
    """One row per scenario, from the core's own figures. The baseline's change
    fields are null. The only arithmetic is the change in the fiscal-year gap
    (gap with the plan less the baseline gap, both the core's) and the plan's
    expected fiscal year (bookings to date plus the core's with-plan forecast)."""
    labels = labels or {s.id: s.label for s in SCENARIOS}
    rows = []
    for scenario, r in reports.items():
        year = r["gap"]["fiscal_year"]
        plan = r.get("plan")
        row = {
            "scenario": scenario,
            "label": labels.get(scenario, scenario),
            "expected_fiscal_year": year["expected"],
            "fiscal_year_gap": year["gap"],
            "bookings_change": None,
            "fiscal_year_gap_change": None,
            "cash_cost_in_twelve_months": None,
        }
        if plan is not None and "unavailable" not in plan:
            signed = reports.get(BASELINE)
            signed_rest = (
                signed["gap"]["fiscal_year"].get("forecast_rest_of_year")
                if signed
                else None
            )
            if signed_rest is not None and plan["baseline"][REST_OF_FY] != signed_rest:
                raise ValueError(
                    f"{scenario}: the plan's baseline {plan['baseline'][REST_OF_FY]} is not the "
                    f"as-signed forecast {signed_rest}"
                )
            fy = plan["gap"]["fiscal_year"]
            to_date = Decimal(year["actual_to_date"])
            row["expected_fiscal_year"] = (
                f"{to_date + Decimal(plan['with_plan'][REST_OF_FY]):.2f}"
            )
            row["fiscal_year_gap"] = fy["gap_with_plan"]
            row["fiscal_year_gap_change"] = (
                f"{Decimal(fy['gap_with_plan']) - Decimal(fy['baseline_gap']):.2f}"
            )
            row["bookings_change"] = dict(plan["difference"])
            row["cash_cost_in_twelve_months"] = plan["cash_cost_in_twelve_months"]
        rows.append(row)
    return rows


# ---------------------------------------------------------------- building


@contextlib.contextmanager
def in_repo():
    """The reports record paths as the core was given them; give it repo-relative ones."""
    here = Path.cwd()
    os.chdir(REPO)
    try:
        yield
    finally:
        os.chdir(here)


def _profile_facts(company: str) -> dict:
    doc = yaml.safe_load((REPO / PROFILES / company / "profile.yaml").read_text())
    return {"name": doc["org_name"], "description": doc["description"]}


def build(companies=COMPANIES, draws: int = DRAWS, seed: int = SEED) -> dict[str, str]:
    """Every generated report file: path under the reports directory -> text."""
    files: dict[str, str] = {}
    entries = []
    with in_repo():
        for company in companies:
            profile, data = PROFILES / company, DATA / company
            reports = {}
            for sc in SCENARIOS:
                plan = None if sc.plan is None else profile / sc.plan
                reports[sc.id] = build_report(
                    profile, data, AS_OF, draws=draws, seed=seed, plan_path=plan
                )
                files[f"{company}/{sc.id}.json"] = canonical(reports[sc.id])
            require_correct({f"{company}/{k}.json": v for k, v in reports.items()})
            files[f"{company}/comparison.json"] = canonical(
                {
                    "company": company,
                    "as_of": AS_OF.isoformat(),
                    "baseline": BASELINE,
                    "rows": comparison_rows(reports),
                }
            )
            inputs = reports[BASELINE]["inputs"]
            entries.append(
                {
                    "id": company,
                    **_profile_facts(company),
                    "as_of": inputs["as_of"],
                    "fiscal_year": inputs["fiscal_year"],
                    "comparison": f"{company}/comparison.json",
                    "scenarios": [
                        {
                            "id": sc.id,
                            "label": sc.label,
                            "description": sc.description,
                            "plan_file": None
                            if sc.plan is None
                            else (profile / sc.plan).as_posix(),
                            "report": f"{company}/{sc.id}.json",
                        }
                        for sc in SCENARIOS
                    ],
                }
            )
    index = {
        "schema_version": contract.SCHEMA_VERSION,
        "default_company": DEFAULT_COMPANY
        if DEFAULT_COMPANY in companies
        else companies[0],
        "companies": entries,
    }
    files["index.json"] = canonical(index)
    _validate_files(files)
    return files


def _validate_files(files: dict[str, str]) -> None:
    report_validator = contract.validator()
    index_validator = Draft202012Validator(INDEX_SCHEMA)
    comparison_validator = Draft202012Validator(COMPARISON_SCHEMA)
    for name, text in files.items():
        doc = json.loads(text)
        if name == "index.json":
            check = index_validator
        elif name.endswith("/comparison.json"):
            check = comparison_validator
        else:
            check = report_validator
        problems = [
            f"{'/'.join(map(str, e.absolute_path))}: {e.message[:160]}"
            for e in check.iter_errors(doc)
        ]
        if problems:
            raise ValueError(
                f"{name} does not satisfy its schema:\n" + "\n".join(problems[:8])
            )


def require_correct(reports: dict[str, dict]) -> None:
    bad = [
        f"{name}: {r['verdicts']['software_correct']['summary']}"
        for name, r in reports.items()
        if r["verdicts"]["software_correct"]["verdict"] != "yes"
    ]
    if bad:
        raise NotCorrect("software-correct verdict is not yes for " + "; ".join(bad))


# ---------------------------------------------------------------- types


def types_files() -> dict[Path, str]:
    """The TypeScript types, compiled from the schemas by the pinned
    json-schema-to-typescript (``frontend/scripts/generate-types.mjs``)."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        schemas = {
            "report": contract.SCHEMA_PATH,
        }
        for name, schema in (
            ("index", INDEX_SCHEMA),
            ("comparison", COMPARISON_SCHEMA),
        ):
            schemas[name] = tmp / f"{name}.schema.json"
            schemas[name].write_text(canonical(schema))
        out = {}
        for target, sources in (
            ("report.ts", ["report"]),
            ("appFiles.ts", ["index", "comparison"]),
        ):
            dest = tmp / target
            subprocess.run(
                ["node", "scripts/generate-types.mjs", str(dest), *(str(schemas[s]) for s in sources)],
                cwd=REPO / "frontend", check=True,
            )  # fmt: skip
            out[GENERATED / target] = dest.read_text()
        return out


# ---------------------------------------------------------------- writing and verifying


def write(out: Path, files: dict[str, str]) -> None:
    for name, text in files.items():
        path = out / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def differences(out: Path, files: dict[str, str]) -> list[str]:
    """What differs between ``out`` and ``files``, byte for byte; reads only."""
    found = []
    for name, text in sorted(files.items()):
        path = out / name
        if not path.exists():
            found.append(f"{name}: missing")
        elif path.read_bytes() != text.encode():
            found.append(f"{name}: differs")
    if out.exists():
        for path in sorted(out.rglob("*")):
            name = path.relative_to(out).as_posix()
            if path.is_file() and name not in files:
                found.append(f"{name}: not generated")
    return found


def _file_differences(texts: dict[Path, str]) -> list[str]:
    found = []
    for rel, text in sorted(texts.items()):
        path = REPO / rel
        if not path.exists():
            found.append(f"{rel}: missing")
        elif path.read_bytes() != text.encode():
            found.append(f"{rel}: differs")
    return found


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m engine.scripts.generate_app_reports"
    )
    parser.add_argument(
        "--verify", action="store_true",
        help="regenerate to a temporary directory and fail if any committed file differs",
    )  # fmt: skip
    args = parser.parse_args(argv)

    plan_files = scenario_plan_files()
    if args.verify:
        # the scenario plan files are inputs: they must be the filtered plan.yaml before anything is built
        problems = _file_differences(plan_files)
    else:
        for rel, text in plan_files.items():
            (REPO / rel).write_text(text)
        problems = []
    try:
        files = build()
    except NotCorrect as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    types = types_files()
    schema_text = {contract.SCHEMA_PATH.relative_to(REPO): contract.schema_text()}
    if args.verify:
        with tempfile.TemporaryDirectory() as tmp:
            write(Path(tmp), files)
            regenerated = {
                p.relative_to(tmp).as_posix(): p.read_text()
                for p in Path(tmp).rglob("*.json")
            }
            problems += [
                f"{REPORTS}/{p}" for p in differences(REPO / REPORTS, regenerated)
            ]
        problems += _file_differences({**types, **schema_text})
        if problems:
            print(
                "generated app data is stale:", *problems, sep="\n  ", file=sys.stderr
            )
            return 1
        print(
            f"ok: {len(files)} report files, {len(types)} type files and {len(plan_files)} plan files are current"
        )
        return 0
    write(REPO / REPORTS, files)
    for rel, text in {**types, **schema_text}.items():
        path = REPO / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(
        f"wrote {len(files)} report files under {REPORTS}, {len(types)} type files under {GENERATED}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
