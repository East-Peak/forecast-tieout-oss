# ---------------------------------------------------------------- building


@contextlib.contextmanager
def in_repo():
    """The reports record paths as the core was given them; give it repo-relative ones."""
    here = Path.cwd()
    os.chdir(REPO)
    try:
        yield
    finally:
        os.chdir(here)


def _profile_facts(company: str, as_signed: dict) -> dict:
    """The company's name, and the line under it: generated from its as-signed report."""
    doc = yaml.safe_load((REPO / PROFILES / company / "profile.yaml").read_text())
    return {"name": doc["org_name"], "description": company_line(as_signed)}


def build(companies=COMPANIES, draws: int = DRAWS, seed: int = SEED) -> dict[str, str]:
    """Every generated report file: path under the reports directory -> text."""
    files: dict[str, str] = {}
    entries = []
    with in_repo():
        for company in companies:
            profile, data = PROFILES / company, DATA / company
            state = prepare(profile, data, AS_OF, draws, seed)
            reports, plans = {}, {}
            for sc in SCENARIOS:
                path = None if sc.plan is None else profile / sc.plan
                plans[sc.id] = (
                    None if path is None else load_plan(path, AS_OF, state.cap.members)
                )
                reports[sc.id] = finish(state, plans[sc.id], path, company, sc.id)
                files[f"{company}/{sc.id}.json"] = canonical(reports[sc.id])
                files[f"{company}/{sc.id}.md"] = render_markdown(reports[sc.id])
            files.update(lanes_files(company, state, reports, plans))
            require_correct({f"{company}/{k}.json": v for k, v in reports.items()})
            files[f"{company}/comparison.json"] = canonical(
                {
                    "company": company,
                    "as_of": AS_OF.isoformat(),
                    "baseline": BASELINE,
                    "rows": comparison_rows(
                        reports, {sc.id: sc.label for sc in SCENARIOS}
                    ),
                }
            )
            inputs = reports[BASELINE]["inputs"]
            entries.append(
                {
                    "id": company,
                    **_profile_facts(company, reports[BASELINE]),
                    "as_of": inputs["as_of"],
                    "fiscal_year": inputs["fiscal_year"],
                    "comparison": f"{company}/comparison.json",
                    "lanes_basis": f"{company}/lanes-basis.json"
                    if f"{company}/lanes-basis.json" in files
                    else None,
                    "lanes_records": f"{company}/lanes-records.json"
                    if f"{company}/lanes-records.json" in files
                    else None,
                    "scenarios": [
                        {
                            "id": sc.id,
                            "label": sc.label,
                            "description": sc.description,
                            "plan_file": None
                            if sc.plan is None
                            else (profile / sc.plan).as_posix(),
                            "report": f"{company}/{sc.id}.json",
                            "report_markdown": f"{company}/{sc.id}.md",
                            "lanes": f"{company}/lanes-{sc.id}.json",
                            **_owner_files(company, sc.id, files),
                        }
                        for sc in SCENARIOS
                    ],
                }
            )
    index = {
        "schema_version": contract.SCHEMA_VERSION,
        "default_company": DEFAULT_COMPANY
        if DEFAULT_COMPANY in companies
        else companies[0],
        "companies": entries,
    }
    files["index.json"] = canonical(index)
    _validate_files(files)
    return files


def lanes_files(company: str, state, reports: dict, plans: dict) -> dict[str, str]:
    """The company's frozen plan basis and one lanes file per scenario. Where the basis cannot be
    built, every scenario's file says why instead, and there is no basis file."""
    try:
        if state.ground is None:
            raise lanes_basis.BasisUnavailable(state.forecasts[2].unavailable_reason)
        basis = lanes_basis.plan_basis(state)
    except lanes_basis.BasisUnavailable as why:
        return {
            f"{company}/lanes-{sc.id}.json": canonical(
                lanes.unavailable_document(company, sc.id, str(why))
            )
            for sc in SCENARIOS
        }
    basis_doc = lanes_basis.document(basis, company)
    digest = lanes_contract.digest(basis_doc)
    files = {f"{company}/lanes-basis.json": canonical(basis_doc)}
    for sc in SCENARIOS:
        hires, inflows = (
            actions.plan_inputs(state.ground, plans[sc.id])
            if plans[sc.id]
            else ((), ())
        )
        doc = lanes.lanes_document(
            state, basis, reports[sc.id], hires, inflows, company, sc.id, digest
        )
        mine, owners = lanes_split.split(doc)
        files[f"{company}/lanes-{sc.id}.json"] = canonical(mine)
        for seg, owned in owners.items():
            files[f"{company}/{lanes_split.name(sc.id, seg)}"] = lanes_text.text(owned)
    # last, so a scenario's own file is the first one a rule can stop the run on
    files[f"{company}/lanes-records.json"] = lanes_records.text(
        lanes_records.document(state, company)
    )
    return files


def _owner_files(company: str, scenario: str, files: dict) -> dict:
    """The index key naming a scenario's owners files by segment (in the lanes' order), where
    there are any."""
    lanes_doc = json.loads(files[f"{company}/lanes-{scenario}.json"])
    found = {}
    for row in lanes_doc["periods"][0]["rows"][1:]:
        name = f"{company}/{lanes_split.name(scenario, row['path'][1])}"
        if name in files:
            found[row["path"][1]] = name
    return {"lanes_owners": found} if found else {}


def lanes_schema_files() -> dict[Path, str]:
    return {
        path: lanes_contract.schema_text(make()) for path, make in LANES_SCHEMAS.items()
    }


def _lanes_problems(name: str, doc, files: dict[str, str]) -> list[str]:
    """A lanes file against its contract, with the company's basis file and the report of its
    scenario, which the rules compare it with."""
    folder, _, leaf = name.rpartition("/")
    if leaf == "lanes-basis.json":
        return lanes_contract.validate_basis(doc)
    if leaf.startswith("lanes-owners-"):
        scenario = doc["scenario"]
        lanes_doc = json.loads(files[f"{folder}/lanes-{scenario}.json"])
        mine = [
            json.loads(t) for n, t in files.items()
            if n.startswith(f"{folder}/lanes-owners-{scenario}-")
        ]  # fmt: skip
        return lanes_contract.validate_owners(
            doc,
            lanes_doc,
            json.loads(files[f"{folder}/lanes-basis.json"]),
            json.loads(files[f"{folder}/{scenario}.json"]),
        ) + lanes_contract.validate_owner_set(mine, lanes_doc)
    if leaf == "lanes-records.json":
        return [
            f"{sc.id}: {p}"
            for sc in SCENARIOS
            for p in lanes_records_contract.validate(
                doc,
                lanes_split.merge(
                    json.loads(files[f"{folder}/lanes-{sc.id}.json"]),
                    [
                        json.loads(t)
                        for n, t in files.items()
                        if n.startswith(f"{folder}/lanes-owners-{sc.id}-")
                    ],
                ),
            )
        ]
    basis = files.get(f"{folder}/lanes-basis.json")
    report = json.loads(files[f"{folder}/{leaf.removeprefix('lanes-')}"])
    return lanes_contract.validate(doc, None if basis is None else json.loads(basis), report)  # fmt: skip


def _problems(validator: Draft202012Validator, doc) -> list[str]:
    return [
        f"{'/'.join(map(str, e.absolute_path))}: {e.message[:160]}"
        for e in validator.iter_errors(doc)
    ]


def _validate_files(files: dict[str, str]) -> None:
    index_validator = Draft202012Validator(INDEX_SCHEMA)
    comparison_validator = Draft202012Validator(COMPARISON_SCHEMA)
    for name, text in files.items():
        if name.endswith(".md"):
            continue  # the report's readable form: rendered from the report the schema just checked
        doc = json.loads(text)
        if name == "index.json":
            problems = _problems(index_validator, doc)
        elif name.endswith("/comparison.json"):
            problems = _problems(comparison_validator, doc)
        elif "/lanes-" in name:
            problems = _lanes_problems(name, doc, files)
        else:
            problems = contract.validate(doc)
        if problems:
            raise ValueError(
                f"{name} does not satisfy its schema:\n" + "\n".join(problems[:8])
            )


def require_correct(reports: dict[str, dict]) -> None:
    bad = [
        f"{name}: {r['verdicts']['software_correct']['summary']}"
        for name, r in reports.items()
        if r["verdicts"]["software_correct"]["verdict"] != "yes"
    ]
    if bad:
        raise NotCorrect("software-correct verdict is not yes for " + "; ".join(bad))


# ---------------------------------------------------------------- types


def replay_problems(companies=COMPANIES) -> list[str]:
    """Every committed worksheet replayed through the whole forward function: each sensitivity at
    its setting, and each needed-alone setting fed back in as written. Independent of the code
    that wrote the section, so a stale or wrong figure cannot agree with itself."""
    from engine.tieout_core.worksheet_replay import replay

    found: list[str] = []
    with in_repo():
        for company in companies:
            state = prepare(PROFILES / company, DATA / company, AS_OF, DRAWS, SEED)
            for sc in SCENARIOS:
                report = json.loads(
                    (REPO / REPORTS / company / f"{sc.id}.json").read_text()
                )
                plan = (
                    None
                    if sc.plan is None
                    else load_plan(
                        PROFILES / company / sc.plan, AS_OF, state.cap.members
                    )
                )
                found += [
                    f"{company}/{sc.id}: {p}" for p in replay(state, report, plan)
                ]
                doc = json.loads(
                    (REPO / REPORTS / company / f"lanes-{sc.id}.json").read_text()
                )
                hires, inflows = (
                    actions.plan_inputs(state.ground, plan) if plan else ((), ())
                )
                found += [
                    f"{company}/{sc.id}: lanes: {p}"
                    for p in lanes_replay.replay(state, doc, hires, inflows)
                ]
            shard = json.loads(
                (REPO / REPORTS / company / "lanes-records.json").read_text()
            )
            found += [
                f"{company}: records: {p}" for p in lanes_replay.records(state, shard)
            ]
    return found


def types_files() -> dict[Path, str]:
    """The TypeScript types, compiled from the schemas by the pinned
    json-schema-to-typescript (``frontend/scripts/generate-types.mjs``)."""
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        # the schema as the contract module defines it now, so one run carries a contract change through
        schemas = {"report": tmp / "report.schema.json"}
        schemas["report"].write_text(contract.schema_text())
        for name, schema in (
            ("index", INDEX_SCHEMA),
            ("comparison", COMPARISON_SCHEMA),
        ):
            schemas[name] = tmp / f"{name}.schema.json"
            schemas[name].write_text(canonical(schema))
        out = {}
        for target, sources in (
            ("report.ts", ["report"]),
            ("appFiles.ts", ["index", "comparison"]),
        ):
            dest = tmp / target
            subprocess.run(
                ["node", "scripts/generate-types.mjs", str(dest), *(str(schemas[s]) for s in sources)],
                cwd=REPO / "frontend", check=True,
            )  # fmt: skip
            out[GENERATED / target] = dest.read_text()
        return out


# ---------------------------------------------------------------- writing and verifying


def write(out: Path, files: dict[str, str]) -> None:
    for name, text in files.items():
        path = out / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)


def differences(out: Path, files: dict[str, str]) -> list[str]:
    """What differs between ``out`` and ``files``, byte for byte; reads only."""
    found = []
    for name, text in sorted(files.items()):
        path = out / name
        if not path.exists():
            found.append(f"{name}: missing")
        elif path.read_bytes() != text.encode():
            found.append(f"{name}: differs")
    if out.exists():
        for path in sorted(out.rglob("*")):
            name = path.relative_to(out).as_posix()
            if path.is_file() and name not in files:
                found.append(f"{name}: not generated")
    return found


def _file_differences(texts: dict[Path, str]) -> list[str]:
    found = []
    for rel, text in sorted(texts.items()):
        path = REPO / rel
        if not path.exists():
            found.append(f"{rel}: missing")
        elif path.read_bytes() != text.encode():
            found.append(f"{rel}: differs")
    return found


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m engine.scripts.generate_app_reports"
    )
    parser.add_argument(
        "--verify", action="store_true",
        help="regenerate to a temporary directory and fail if any committed file differs, or if a committed worksheet figure does not replay through the model",
    )  # fmt: skip
    args = parser.parse_args(argv)

    plan_files = scenario_plan_files()
    if args.verify:
        # the scenario plan files are inputs: they must be the filtered plan.yaml before anything is built
        problems = _file_differences(plan_files)
    else:
        for rel, text in plan_files.items():
            (REPO / rel).write_text(text)
        problems = []
    try:
        files = build()
    except NotCorrect as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    types = types_files()
    schema_text = {
        contract.SCHEMA_PATH.relative_to(REPO): contract.schema_text(),
        **lanes_schema_files(),
    }
    if args.verify:
        with tempfile.TemporaryDirectory() as tmp:
            write(Path(tmp), files)
            regenerated = {
                p.relative_to(tmp).as_posix(): p.read_text()
                for p in Path(tmp).rglob("*")
                if p.is_file()
            }
            problems += [
                f"{REPORTS}/{p}" for p in differences(REPO / REPORTS, regenerated)
            ]
        problems += _file_differences({**types, **schema_text})
        problems += replay_problems()
        if problems:
            print(
                "generated app data is stale:", *problems, sep="\n  ", file=sys.stderr
            )
            return 1
        print(
            f"ok: {len(files)} report files, {len(types)} type files and {len(plan_files)} plan files are current"
        )
        return 0
    write(REPO / REPORTS, files)
    for rel, text in {**types, **schema_text}.items():
        path = REPO / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    print(
        f"wrote {len(files)} report files under {REPORTS}, {len(types)} type files under {GENERATED}"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
