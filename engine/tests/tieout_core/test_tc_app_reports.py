# ---------------------------------------------------------------- write and verify


def test_verify_passes_on_what_was_just_written_and_fails_on_a_changed_byte(
    tmp_path, built
):
    out = tmp_path / "reports"
    gen.write(out, built)
    assert gen.differences(out, built) == []
    path = out / COMPANY / "as-signed.json"
    path.write_text(path.read_text().replace("2026-08-31", "2026-08-30", 1))
    assert gen.differences(out, built) == [f"{COMPANY}/as-signed.json: differs"]


def test_verify_reports_a_missing_and_a_stray_file(tmp_path, built):
    out = tmp_path / "reports"
    gen.write(out, built)
    (out / COMPANY / "hires-only.json").unlink()
    (out / "stray.json").write_text("{}\n")
    found = gen.differences(out, built)
    assert f"{COMPANY}/hires-only.json: missing" in found
    assert "stray.json: not generated" in found


def test_a_report_whose_software_is_not_correct_stops_the_generator(built):
    r = json.loads(built[f"{COMPANY}/as-signed.json"])
    r["verdicts"]["software_correct"]["verdict"] = "no"
    r["verdicts"]["software_correct"]["summary"] = "failed x"
    with pytest.raises(gen.NotCorrect, match="as-signed"):
        gen.require_correct({f"{COMPANY}/as-signed.json": r})


def test_verify_does_not_rewrite_the_directory(tmp_path, built):
    out = tmp_path / "reports"
    gen.write(out, built)
    before = {p: p.read_bytes() for p in out.rglob("*.json")}
    gen.differences(out, built)
    assert before == {p: p.read_bytes() for p in out.rglob("*.json")}
    shutil.rmtree(out)


def test_a_changed_byte_in_a_report_md_is_a_difference(tmp_path, built):
    out = tmp_path / "reports"
    gen.write(out, built)
    md = out / COMPANY / "as-signed.md"
    md.write_text(md.read_text() + "x")
    assert gen.differences(out, built) == [f"{COMPANY}/as-signed.md: differs"]


def test_a_records_shard_that_disagrees_with_the_lanes_stops_the_generator(built):
    files = dict(built)
    shard = json.loads(files[f"{COMPANY}/lanes-records.json"])
    row = next(r for r in shard["rows"] if r["periods"]["FY26"]["created"])
    row["periods"]["FY26"]["created"].pop()
    files[f"{COMPANY}/lanes-records.json"] = lanes_records.text(shard)
    with pytest.raises(ValueError, match="lanes-records"):
        gen._validate_files(files)
