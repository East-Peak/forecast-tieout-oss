# ---------------------------------------------------------------- scenario plan files


PLAN = """\
# header comment
hires:
  - {segment: mid_market, start: 2026-10, count: 2}
programs:
  - {name: Referrals, pipeline: 600000, start: 2026-10}
"""


def test_hires_only_keeps_the_hires_and_drops_the_programs():
    doc = yaml.safe_load(gen.filter_plan(PLAN, "hires-only"))
    assert doc == {"hires": [{"segment": "mid_market", "start": "2026-10", "count": 2}]}


def test_program_only_keeps_the_programs_and_drops_the_hires():
    doc = yaml.safe_load(gen.filter_plan(PLAN, "program-only"))
    assert doc == {
        "programs": [{"name": "Referrals", "pipeline": 600000, "start": "2026-10"}]
    }


def test_a_filtered_plan_says_where_it_came_from():
    text = gen.filter_plan(PLAN, "hires-only")
    assert text.startswith("# Generated by engine/scripts/generate_app_reports.py")
    assert "plan.yaml" in text.splitlines()[0] or "plan.yaml" in text.splitlines()[1]


def test_an_unknown_scenario_filter_is_refused():
    with pytest.raises(ValueError):
        gen.filter_plan(PLAN, "everything")


@pytest.mark.parametrize("company", gen.COMPANIES)
def test_the_committed_scenario_plan_files_are_the_filtered_demo_plan(company):
    profile = gen.PROFILES / company
    demo = (profile / "plan.yaml").read_text()
    for scenario in ("hires-only", "program-only"):
        committed = (profile / f"plan-{scenario}.yaml").read_text()
        assert committed == gen.filter_plan(demo, scenario)


# ---------------------------------------------------------------- canonical files


def test_canonical_json_has_stable_key_order_and_one_trailing_newline():
    a = gen.canonical({"b": 1, "a": {"d": 2, "c": [3, {"z": 1, "y": 2}]}})
    b = gen.canonical({"a": {"c": [3, {"y": 2, "z": 1}], "d": 2}, "b": 1})
    assert a == b
    assert a.endswith("}\n") and not a.endswith("\n\n")
    assert a.index('"a"') < a.index('"b"')


# ---------------------------------------------------------------- types come from the schema in memory


def test_types_are_generated_from_the_schema_in_memory_not_the_committed_copy(
    monkeypatch,
):
    """A contract change must reach the types in one run: the schema handed to the type
    generator is contract.schema_text() as it is now, not report.schema.json as it was."""
    monkeypatch.setattr(
        gen.contract, "schema_text", lambda: '{"title": "FromMemory"}\n'
    )
    seen = []

    def fake_run(args, cwd, check):
        seen.append([Path(a).read_text() for a in args[3:]])
        Path(args[2]).write_text("// types\n")

    monkeypatch.setattr(gen.subprocess, "run", fake_run)
    gen.types_files()
    assert seen[0] == ['{"title": "FromMemory"}\n']


