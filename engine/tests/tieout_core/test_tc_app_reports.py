def test_each_report_validates_is_correct_and_carries_its_scenarios_plan(built):
    expected_plan = {
        "as-signed": None,
        "demo-plan": "plan.yaml",
        "hires-only": "plan-hires-only.yaml",
        "program-only": "plan-program-only.yaml",
    }
    for scenario, plan_name in expected_plan.items():
        r = json.loads(built[f"{COMPANY}/{scenario}.json"])
        assert list(contract.validator().iter_errors(r)) == []
        assert r["verdicts"]["software_correct"]["verdict"] == "yes"
        assert r["inputs"]["simulation"] == {"draws": 2000, "seed": 0}
        if plan_name is None:
            assert "plan" not in r
        else:
            assert r["plan"]["file"] == f"engine/config/profiles/{COMPANY}/{plan_name}"


