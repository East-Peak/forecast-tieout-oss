def test_the_comparison_file_ties_to_the_reports(built):
    comp = json.loads(built[f"{COMPANY}/comparison.json"])
    signed = json.loads(built[f"{COMPANY}/as-signed.json"])
    plan = json.loads(built[f"{COMPANY}/demo-plan.json"])
    rows = {r["scenario"]: r for r in comp["rows"]}
    assert (
        rows["as-signed"]["expected_fiscal_year"]
        == signed["gap"]["fiscal_year"]["expected"]
    )
    assert (
        rows["demo-plan"]["fiscal_year_gap"]
        == plan["plan"]["gap"]["fiscal_year"]["gap_with_plan"]
    )
    assert rows["demo-plan"]["bookings_change"] == plan["plan"]["difference"]
    assert Decimal(rows["demo-plan"]["fiscal_year_gap_change"]) == Decimal(
        plan["plan"]["gap"]["fiscal_year"]["gap_with_plan"]
    ) - Decimal(plan["plan"]["gap"]["fiscal_year"]["baseline_gap"])


