// Compile JSON Schemas to TypeScript types with the pinned json-schema-to-typescript.
//   node scripts/generate-types.mjs <out.ts> <schema.json> [<schema.json> ...]
// Run by `python -m engine.scripts.generate_app_reports`, which owns the schemas and
// checks the committed output is current (`--verify`).
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const [out, ...schemas] = process.argv.slice(2);
if (!out || schemas.length === 0) {
  console.error("usage: generate-types.mjs <out.ts> <schema.json> [...]");
  process.exit(2);
}

const banner = `/* eslint-disable */
/**
 * GENERATED by engine/scripts/generate_app_reports.py (json-schema-to-typescript).
 * Do not edit: change engine/tieout_core/contract.py or the script, then regenerate.
 */
`;

const parts = [];
for (const file of schemas) {
  const schema = JSON.parse(await readFile(file, "utf8"));
  parts.push(
    await compile(schema, schema.title ?? "Schema", {
      bannerComment: "",
      additionalProperties: false,
      strictIndexSignatures: true,
      cwd: ".",
    }),
  );
}
// Report decimals are branded strings, so arithmetic on one is a compile error (see src/__tests__/noArithmetic.test.ts).
const branded = parts
  .join("\n")
  .replace(/export type (Money|Decimal) = string;/g, "export type $1 = string & { readonly __decimal: true };");
await writeFile(out, banner + branded);
